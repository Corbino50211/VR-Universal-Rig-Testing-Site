using System.Collections.Generic;
using UnityEngine;
using UnityEngine.InputSystem;
using UnityEngine.InputSystem.XR.Haptics;
using UnityEngine.XR;

namespace UniversalRig
{
    // Sole writer of the tracked nodes. Do not put another tracked pose driver on them.
    [DefaultExecutionOrder(-300)]
    public sealed class RigInput : MonoBehaviour
    {
        [Tooltip("Serialized action asset generated by RigBuilder so OpenXR can discover bindings before session startup.")]
        public InputActionAsset actionsAsset;
        public Transform trackingSpace;
        public Transform head;
        public Transform leftTarget;
        public Transform rightTarget;
        [Tooltip("Used only when the XR runtime reports Device tracking origin.")]
        public float deviceStandingHeight = 1.7f;
        [Range(0.5f, 1.5f)] public float trackingScale = 1f;

        public bool HeadTracked { get; private set; }
        public bool LeftTracked { get; private set; }
        public bool RightTracked { get; private set; }
        public Vector2 Move { get; private set; }
        public Vector2 Turn { get; private set; }
        public float LeftGrip { get; private set; }
        public float RightGrip { get; private set; }
        public float LeftTrigger { get; private set; }
        public float RightTrigger { get; private set; }
        public bool FloorMode { get; private set; }
        // False until the tracking origin mode has been checked once; don't calibrate before.
        public bool OriginReady { get; private set; }
        public float RawHeadHeight => headPosition.ReadValue<Vector3>().y + (FloorMode ? 0f : deviceStandingHeight);

        private InputActionMap actions;
        private InputAction headPosition, headRotation, headTracked, headState;
        private InputAction leftPosition, leftRotation, leftTracked, leftState;
        private InputAction rightPosition, rightRotation, rightTracked, rightState;
        private InputAction move, turn, leftGrip, rightGrip, leftTrigger, rightTrigger, jump, calibrate;
        private readonly List<XRInputSubsystem> subsystems = new List<XRInputSubsystem>();
        private float nextOriginCheck;
        private bool jumpQueued, calibrationQueued, recenterQueued;
        private XRInputSubsystem originSource;

        private void Awake()
        {
            if (!actionsAsset)
            {
                Debug.LogError("Universal Rig: assign the serialized input action asset before starting OpenXR.", this);
                enabled = false;
                return;
            }
            actions = actionsAsset.FindActionMap("UniversalRig", true);
            headPosition = actions.FindAction("HeadPosition", true);
            headRotation = actions.FindAction("HeadRotation", true);
            headTracked = actions.FindAction("HeadTracked", true);
            headState = actions.FindAction("HeadState", true);
            leftPosition = actions.FindAction("LeftPosition", true);
            leftRotation = actions.FindAction("LeftRotation", true);
            leftTracked = actions.FindAction("LeftTracked", true);
            leftState = actions.FindAction("LeftState", true);
            rightPosition = actions.FindAction("RightPosition", true);
            rightRotation = actions.FindAction("RightRotation", true);
            rightTracked = actions.FindAction("RightTracked", true);
            rightState = actions.FindAction("RightState", true);
            move = actions.FindAction("Move", true);
            turn = actions.FindAction("Turn", true);
            leftGrip = actions.FindAction("LeftGrip", true);
            rightGrip = actions.FindAction("RightGrip", true);
            leftTrigger = actions.FindAction("LeftTrigger", true);
            rightTrigger = actions.FindAction("RightTrigger", true);
            jump = actions.FindAction("Jump", true);
            calibrate = actions.FindAction("Calibrate", true);
        }

        private void OnEnable()
        {
            if (actions == null) return;
            jump.performed += QueueJump;
            calibrate.performed += QueueCalibration;
            actions.Enable();
            nextOriginCheck = 0f;
            Application.onBeforeRender += RefreshPoses;
        }

        private void OnDisable()
        {
            Application.onBeforeRender -= RefreshPoses;
            WatchOrigin(null);
            if (actions != null)
            {
                jump.performed -= QueueJump;
                calibrate.performed -= QueueCalibration;
                actions.Disable();
            }
            jumpQueued = calibrationQueued = recenterQueued = false;
            HeadTracked = LeftTracked = RightTracked = false;
            OriginReady = false;
            Move = Turn = Vector2.zero;
            LeftGrip = RightGrip = LeftTrigger = RightTrigger = 0f;
        }

        private void QueueJump(InputAction.CallbackContext _) { jumpQueued = true; }
        private void QueueCalibration(InputAction.CallbackContext _) { calibrationQueued = true; }
        public bool ConsumeJump() { bool result = jumpQueued; jumpQueued = false; return result; }
        public bool ConsumeCalibration() { bool result = calibrationQueued; calibrationQueued = false; return result; }
        // Set when the runtime recenters (system menu) so the rig can re-align the head over the body.
        public bool ConsumeRecenter() { bool result = recenterQueued; recenterQueued = false; return result; }
        private void QueueRecenter(XRInputSubsystem _) { recenterQueued = true; }

        private void WatchOrigin(XRInputSubsystem subsystem)
        {
            if (originSource == subsystem) return;
            if (originSource != null) originSource.trackingOriginUpdated -= QueueRecenter;
            originSource = subsystem;
            if (originSource != null) originSource.trackingOriginUpdated += QueueRecenter;
        }

        private void Update()
        {
            if (Time.unscaledTime >= nextOriginCheck)
            {
                nextOriginCheck = Time.unscaledTime + 1f;
                bool wasFloor = FloorMode;
                SubsystemManager.GetSubsystems(subsystems);
                foreach (XRInputSubsystem subsystem in subsystems)
                {
                    if (!subsystem.running) continue;
                    if (subsystem.GetTrackingOriginMode() != TrackingOriginModeFlags.Floor)
                        subsystem.TrySetTrackingOriginMode(TrackingOriginModeFlags.Floor);
                    FloorMode = subsystem.GetTrackingOriginMode() == TrackingOriginModeFlags.Floor;
                    WatchOrigin(subsystem);
                    break;
                }
                // Height calibration measured in the wrong origin mode is invalid; redo it.
                if (OriginReady && wasFloor != FloorMode) calibrationQueued = true;
                OriginReady = true;
            }
            RefreshPoses();
            Move = LeftTracked ? Vector2.ClampMagnitude(move.ReadValue<Vector2>(), 1f) : Vector2.zero;
            Turn = RightTracked ? Vector2.ClampMagnitude(turn.ReadValue<Vector2>(), 1f) : Vector2.zero;
            LeftGrip = LeftTracked ? leftGrip.ReadValue<float>() : 0f;
            RightGrip = RightTracked ? rightGrip.ReadValue<float>() : 0f;
            LeftTrigger = LeftTracked ? leftTrigger.ReadValue<float>() : 0f;
            RightTrigger = RightTracked ? rightTrigger.ReadValue<float>() : 0f;
        }

        // Input System 1.20 XR haptic command. No-op when the binding has no device (editor without a runtime).
        public void Pulse(bool left, float amplitude, float duration)
        {
            InputAction action = left ? leftGrip : rightGrip;
            if (action == null) return;
            UnityEngine.InputSystem.InputDevice device = action.activeControl != null ? action.activeControl.device
                : (action.controls.Count > 0 ? action.controls[0].device : null);
            if (device == null) return;
            SendHapticImpulseCommand command = SendHapticImpulseCommand.Create(0,
                Mathf.Clamp01(amplitude), Mathf.Clamp(duration, 0f, 0.1f));
            device.ExecuteCommand(ref command);
        }

        public void RefreshPoses()
        {
            if (actions == null || !actions.enabled) return;
            HeadTracked = ApplyPose(head, headPosition, headRotation, headTracked, headState);
            LeftTracked = ApplyPose(leftTarget, leftPosition, leftRotation, leftTracked, leftState);
            RightTracked = ApplyPose(rightTarget, rightPosition, rightRotation, rightTracked, rightState);
        }

        private bool ApplyPose(Transform node, InputAction position, InputAction rotation,
            InputAction tracked, InputAction state)
        {
            const int validPoseBits = (int)(InputTrackingState.Position | InputTrackingState.Rotation);
            bool valid = node && tracked.ReadValue<float>() > 0.5f &&
                (state.ReadValue<int>() & validPoseBits) == validPoseBits;
            if (!valid) return false;
            Vector3 local = position.ReadValue<Vector3>();
            if (!FloorMode) local.y += deviceStandingHeight;
            node.SetLocalPositionAndRotation(local * trackingScale, rotation.ReadValue<Quaternion>());
            return true;
        }
    }
}
